// Generates src/lib/countries.ts (ISO code, English name, calling code) from libphonenumber-js and ICU. Run: node scripts/make-countries.mjs
import { getCountries, getCountryCallingCode } from "libphonenumber-js";
import { writeFileSync } from "node:fs";
const dn = new Intl.DisplayNames(["en"], { type: "region" });
const rows = getCountries().filter((c) => !["AC", "TA", "XK"].includes(c)).map((c) => [c, dn.of(c), getCountryCallingCode(c)]).filter(([, n, d]) => n && n !== c0(n) && d).sort((a, b) => a[1].localeCompare(b[1]));
function c0(n) { return n.length === 2 ? n : ""; }
const body = `/** Generated by scripts/make-countries.mjs from libphonenumber-js and ICU. Do not edit by hand. */
export const COUNTRIES: [iso: string, name: string, dial: string][] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL("../src/lib/countries.ts", import.meta.url), body + `
/** Markets we focus on, shown first in country lists. */
export const PRIORITY_COUNTRIES = ["US", "GB", "CA", "DE", "NL", "AU", "IE", "FR", "ES", "IT", "SE", "NO", "DK", "FI", "BE", "AT", "CH", "PL", "PT"];
export const COUNTRY_NAME: Record<string, string> = Object.fromEntries(COUNTRIES.map(([c, n]) => [c, n]));
export const DIAL: Record<string, string> = Object.fromEntries(COUNTRIES.map(([c, , d]) => [c, d]));
export const isCountry = (c: string) => c in COUNTRY_NAME;
`);
console.log(rows.length + " countries");
