def las_bytes(xyz, units_key=None, vert_key=None, cls=None, rgb=None, intensity=None, crs_code=None) -> bytes:
    """A real LAS/LAZ file built with laspy. units_key/vert_key are EPSG linear-unit codes (9001 metre, 9002 foot, 9003 US foot) written as GeoTIFF keys."""
    import io

    import laspy
    fmt = 3 if rgb is not None else 1
    hdr = laspy.LasHeader(point_format=fmt, version="1.4")
    hdr.scales, hdr.offsets = [0.001] * 3, [float(np.floor(v)) for v in np.min(xyz, axis=0)]
    keys = [(1024, 0, 1, 1)]
    if crs_code:
        keys.append((3072, 0, 1, crs_code))
    if units_key:
        keys.append((3076, 0, 1, units_key))
    if vert_key:
        keys.append((4099, 0, 1, vert_key))
    if len(keys) > 1:
        gk = struct.pack("<4H", 1, 1, 0, len(keys)) + b"".join(struct.pack("<4H", *k) for k in keys)
        hdr.vlrs.append(laspy.VLR(user_id="LASF_Projection", record_id=34735, description="GeoKeyDirectoryTag", record_data=gk))
    las = laspy.LasData(hdr)
    las.x, las.y, las.z = xyz[:, 0], xyz[:, 1], xyz[:, 2]
    if cls is not None:
        las.classification = cls
    if rgb is not None:
        las.red, las.green, las.blue = rgb[:, 0].astype(np.uint16) * 257, rgb[:, 1].astype(np.uint16) * 257, rgb[:, 2].astype(np.uint16) * 257
    if intensity is not None:
        las.intensity = intensity
    b = io.BytesIO()
    las.write(b)
    return b.getvalue()


def flat_scene(n=20000, seed=0, size=60.0):
    rng = np.random.default_rng(seed)
    return np.c_[rng.uniform(0, size, n), rng.uniform(0, size, n), rng.normal(0, 0.02, n)]


