import csv
import io
import json
import time
import uuid
from collections import defaultdict, deque
from contextlib import asynccontextmanager

from fastapi import Body, FastAPI, File, Form, HTTPException, Query, Request, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, Response

from . import bi, summary
from .config import Settings
from .db import NAME, Rejected, Store, is_collection
from .flow import TRIGGERS, Engine, validate_workflow
from .schema import SLICES, SPECS, stock_map


def split_state(state: dict) -> tuple[dict, dict]:
    up, sc = {}, {}
    for k, v in state.items():
        if is_collection(v):
            up[k] = v
        elif isinstance(v, list) and not v:
            continue
        else:
            sc[k] = v
    return up, sc


def create_app(settings: Settings | None = None) -> FastAPI:
    s = settings or Settings()
    st: dict = {}
    hits: dict[str, deque] = defaultdict(deque)

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        store = Store(s.db_path, s.max_records_per_ws, s.max_workspaces, s.ws_ttl_days)
        st["store"], st["engine"] = store, Engine(store)
        app.state.store = store
        yield

    app = FastAPI(title="Neo Forge business demo API", version="1.0.0", lifespan=lifespan,
                  description="Persistence, validation, summaries, workflow execution and data import for the fictional CRM / HRM / ERP demos. Demo data only.")
    app.add_middleware(CORSMiddleware, allow_origins=list(s.allowed_origins), allow_methods=["GET", "POST", "PUT", "PATCH", "DELETE"], allow_headers=["*"])

    @app.middleware("http")
    async def guard(request: Request, call_next):
        cl = request.headers.get("content-length")
        if cl and cl.isdigit() and int(cl) > s.max_body_kb * 1024 and "/bi/import" not in request.url.path:
            return JSONResponse({"detail": f"The request is larger than {s.max_body_kb} KB."}, status_code=413)
        ip = request.client.host if request.client else "?"
        q = hits[ip]
        now = time.time()
        while q and q[0] < now - 60:
            q.popleft()
        if len(q) >= s.rate_per_minute:
            return JSONResponse({"detail": "Too many requests. Please slow down."}, status_code=429, headers={"Retry-After": "10"})
        q.append(now)
        return await call_next(request)

    store = lambda: st["store"]  # noqa: E731
    eng = lambda: st["engine"]  # noqa: E731

    @app.exception_handler(Rejected)
    async def rejected(_: Request, e: Rejected):
        return JSONResponse({"detail": str(e), "errors": e.errors}, status_code=e.status)

    @app.exception_handler(Exception)
    async def unhandled(_: Request, exc: Exception):
        return JSONResponse({"detail": "Internal error."}, status_code=500)

    def sl_ok(sl: str) -> str:
        if sl not in SLICES:
            raise HTTPException(404, f"Unknown module '{sl}'.")
        return sl

    def coll_ok(c: str) -> str:
        if not NAME.match(c):
            raise HTTPException(404, "Unknown collection.")
        return c

    def after_create(ws: str, sl: str, created: list[tuple[str, str]]) -> dict:
        runs = []
        for coll, rid in created:
            if (sl, coll) in TRIGGERS:
                rec = next((r for r in store().slice(ws, sl).get(coll, []) if r["id"] == rid), None)
                if rec:
                    runs += eng().on_created(ws, sl, coll, rec)
        return {"workflow_runs": [{"id": r["id"], "workflow": r["workflowName"], "status": r["status"]} for r in runs], "refresh": ["flow", "crm", "desk", "hrm", "proc"] if runs else []}

    # ---- meta ------------------------------------------------------------------------------------------------------------
    @app.get("/api/health")
    def health():
        return {"ok": True, "storage": "sqlite", "slices": sorted(SLICES), "limits": {"max_body_kb": s.max_body_kb, "max_records_per_workspace": s.max_records_per_ws, "workspace_ttl_days": s.ws_ttl_days}}

    # ---- workspace state -------------------------------------------------------------------------------------------------
    @app.get("/api/biz/{ws}/state")
    def get_state(ws: str):
        store().ensure_ws(ws)
        return {"workspace": ws, "slices": store().state(ws)}

    @app.delete("/api/biz/{ws}")
    def delete_ws(ws: str):
        store().ensure_ws(ws)
        store().delete_ws(ws)
        return {"deleted": True}

    @app.put("/api/biz/{ws}/{sl}")
    def put_slice(ws: str, sl: str, body: dict = Body(...)):
        sl_ok(sl)
        state = body.get("state")
        if not isinstance(state, dict):
            raise HTTPException(400, "Send {\"state\": {...}}.")
        up, sc = split_state(state)
        return store().apply(ws, sl, upsert=up, scalars=sc, replace=True) | {"counts": {k: len(v) for k, v in up.items()}}

    @app.delete("/api/biz/{ws}/{sl}")
    def delete_slice(ws: str, sl: str):
        sl_ok(sl)
        store().ensure_ws(ws)
        store().clear_slice(ws, sl)
        return {"cleared": True}

    @app.post("/api/biz/{ws}/{sl}/ops")
    def ops(ws: str, sl: str, body: dict = Body(...)):
        sl_ok(sl)
        if not isinstance(body, dict) or not set(body) <= {"upsert", "delete", "order", "scalars", "drop_scalars"}:
            raise HTTPException(400, "Send upsert, delete, order, scalars and/or drop_scalars.")
        r = store().apply(ws, sl, body.get("upsert"), body.get("delete"), body.get("order"), body.get("scalars"), body.get("drop_scalars"))
        return {"ok": True, **after_create(ws, sl, r["created"])}

    # ---- summaries ------------------------------------------------------------------------------------------------------
    @app.get("/api/biz/{ws}/summary/{sl}")
    def summarise(ws: str, sl: str):
        if sl not in summary.SUMMARIES:
            raise HTTPException(404, "No summary for this module.")
        store().ensure_ws(ws)
        data = store().slice(ws, sl)
        if not data:
            raise HTTPException(409, "This module has no data in the workspace yet.")
        return {"module": sl, "computed_from": "stored records", "summary": summary.SUMMARIES[sl](data)}

    # ---- domain operations ------------------------------------------------------------------------------------------------
    @app.post("/api/biz/{ws}/inv/movements", status_code=201)
    def stock_movement(ws: str, body: dict = Body(...)):
        """Record one stock movement. The quantity is given as a positive number; the sign follows the movement type. Rejected when it would make stock negative."""
        t, q = body.get("type"), body.get("qty")
        if t not in ("Receipt", "Issue", "Adjustment", "Transfer"):
            raise HTTPException(400, "type must be Receipt, Issue, Adjustment or Transfer.")
        if isinstance(q, bool) or not isinstance(q, (int, float)) or q == 0 or q != q:
            raise HTTPException(400, "qty must be a non-zero number.")
        if t != "Adjustment" and q < 0:
            raise HTTPException(400, "qty must be positive; the movement type decides whether stock goes up or down.")
        pid, wh = body.get("productId"), body.get("whId")
        inv = store().slice(ws, "inv")
        if not inv:
            raise HTTPException(409, "The inventory module has no data in this workspace yet.")
        day = body.get("date") or "2026-03-15"
        mv_id = lambda: f"mv_{uuid.uuid4().hex[:8]}"  # noqa: E731
        base = {"date": day, "productId": pid, "ref": str(body.get("ref", ""))[:60], "note": str(body.get("note", ""))[:200]}
        if t == "Transfer":
            to = body.get("toWhId")
            if not to or to == wh:
                raise HTTPException(400, "A transfer needs a different toWhId.")
            new = [{**base, "id": mv_id(), "whId": wh, "type": "Transfer out", "qty": -abs(q)}, {**base, "id": mv_id(), "whId": to, "type": "Transfer in", "qty": abs(q)}]
        else:
            new = [{**base, "id": mv_id(), "whId": wh, "type": t, "qty": q if t != "Issue" else -abs(q), **({"unitCost": body["unitCost"]} if isinstance(body.get("unitCost"), (int, float)) else {})}]
        store().apply(ws, "inv", {"movements": new})
        sm = stock_map(store().slice(ws, "inv")["movements"])
        return {"movements": new, "on_hand_in_warehouse": sm.get((pid, wh), 0), "on_hand_total": sum(v for (p, _), v in sm.items() if p == pid)}

    @app.post("/api/biz/{ws}/fin/{coll}/{rid}/payments", status_code=201)
    def add_payment(ws: str, coll: str, rid: str, body: dict = Body(...)):
        if coll not in ("invoices", "bills"):
            raise HTTPException(404, "Payments apply to invoices or bills.")
        doc = find(ws, "fin", coll, rid)
        amt = body.get("amount")
        if isinstance(amt, bool) or not isinstance(amt, (int, float)) or amt <= 0:
            raise HTTPException(400, "amount must be a positive number.")
        pay = {"id": f"pay_{uuid.uuid4().hex[:8]}", "date": body.get("date") or "2026-03-15", "amount": round(float(amt), 2), "method": str(body.get("method", "Bank transfer"))[:40], "ref": str(body.get("ref", ""))[:60]}
        if coll == "invoices" and doc.get("draft"):
            raise HTTPException(409, "A draft invoice cannot receive payments; issue it first.")
        store().apply(ws, "fin", {coll: [{**doc, "payments": [*doc.get("payments", []), pay]}]})
        from .schema import doc_total
        paid = sum(p["amount"] for p in doc.get("payments", [])) + pay["amount"]
        return {"payment": pay, "total": doc_total(doc), "paid": round(paid, 2), "balance": round(doc_total(doc) - paid, 2)}

    @app.post("/api/biz/{ws}/proc/orders/{rid}/receive", status_code=201)
    def receive(ws: str, rid: str, body: dict = Body(...)):
        """Record a goods receipt against a purchase order and add the received quantities to the inventory ledger, in two consistent steps."""
        po = find(ws, "proc", "orders", rid)
        if po["status"] not in ("Sent", "Partially received"):
            raise HTTPException(409, f"A {po['status']} order cannot receive goods; send it first." if po["status"] in ("Draft",) else f"A {po['status']} order cannot receive goods.")
        lines = body.get("lines")
        if not isinstance(lines, list) or not lines:
            raise HTTPException(400, "Send lines: [{productId, qty}].")
        wh = body.get("whId") or po.get("whId")
        new_lines = [dict(l) for l in po["lines"]]
        got = []
        for r in lines:
            q = r.get("qty")
            if isinstance(q, bool) or not isinstance(q, (int, float)) or q <= 0:
                raise HTTPException(400, "Each received quantity must be a positive number.")
            ln = next((l for l in new_lines if l["productId"] == r.get("productId")), None)
            if not ln:
                raise HTTPException(400, f"{r.get('productId')} is not on this order.")
            if ln["received"] + q > ln["qty"] + 1e-9:
                raise HTTPException(409, f"{r['productId']}: receiving {q} would exceed the ordered {ln['qty']} (already received {ln['received']}).")
            ln["received"] += q
            got.append({"productId": ln["productId"], "qty": q})
        full = all(l["received"] >= l["qty"] for l in new_lines)
        receipt = {"id": f"grn_{uuid.uuid4().hex[:8]}", "number": f"GRN-{uuid.uuid4().hex[:5].upper()}", "date": body.get("date") or "2026-03-15", "whId": wh, "by": str(body.get("by", ""))[:40], "note": str(body.get("note", ""))[:200], "lines": got}
        updated = {**po, "lines": new_lines, "status": "Received" if full else "Partially received", "receipts": [*po.get("receipts", []), receipt]}
        invd = store().slice(ws, "inv")
        moves = []
        if invd:  # only when the inventory module exists in this workspace
            moves = [{"id": f"mv_{uuid.uuid4().hex[:8]}", "date": receipt["date"], "productId": g["productId"], "whId": wh, "type": "Receipt", "qty": g["qty"], "unitCost": next(l["price"] for l in new_lines if l["productId"] == g["productId"]), "ref": receipt["number"], "note": f"Goods receipt for {po['number']}"} for g in got]
        store().apply(ws, "proc", {"orders": [updated]})
        try:
            if moves:
                store().apply(ws, "inv", {"movements": moves})
        except Rejected:
            store().apply(ws, "proc", {"orders": [po]})  # undo the order change so the two modules stay consistent
            raise
        return {"order_status": updated["status"], "receipt": receipt, "inventory_movements": len(moves), "inventory_updated": bool(moves)}

