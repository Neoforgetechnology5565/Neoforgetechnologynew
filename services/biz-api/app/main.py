"""Neo Forge business demo API: record-level persistence (SQLite), validation, summaries, domain operations, a rule-based workflow engine and BI import for the
CRM / HRM / ERP demos. Workspaces are anonymous: the id (16-32 hex characters) is generated by the browser and is the only key to its data."""
